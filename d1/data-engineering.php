<script>
document.querySelectorAll(".js-marquee").forEach(marquee => {
  const track = marquee.querySelector(".js-marquee-track");

  // Duplicate content once
  track.innerHTML += track.innerHTML;

  let position = 0;
  let speed = 0.5; // adjust speed here
  let isPaused = false;

  // Pause on hover
  marquee.addEventListener("mouseenter", () => isPaused = true);
  marquee.addEventListener("mouseleave", () => isPaused = false);

  function animate() {
    if (!isPaused) {
      position -= speed;

      // Reset when half scrolled
      if (Math.abs(position) >= track.scrollWidth / 2) {
        position = 0;
      }

      track.style.transform = `translateX(${position}px)`;
    }

    requestAnimationFrame(animate);
  }

  animate();
});
</script>


