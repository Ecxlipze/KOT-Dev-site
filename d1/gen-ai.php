  <script>
    const slider = document.getElementById("aiSlider");
    const cards = document.querySelectorAll(".achieve-card");

    let index = 0;
    let cardWidth = cards[0].offsetWidth + 20; // card + gap
    let interval;

    // Clone cards for infinite effect
    cards.forEach(card => {
      track.appendChild(card.cloneNode(true));
    });

    // Auto slide
    function startSlider() {
      interval = setInterval(() => {
        index++;
        track.style.transform = `translateX(-${index * cardWidth}px)`;

        // Reset seamlessly
        if (index === cards.length) {
          setTimeout(() => {
            track.style.transition = "none";
            index = 0;
            track.style.transform = `translateX(0)`;

            requestAnimationFrame(() => {
              track.style.transition = "transform 0.6s ease-in-out";
            });
          }, 600);
        }
      }, 2500);
    }

    // Manual controls
    document.querySelector(".slider-btn.right").onclick = () => {
      clearInterval(interval);
      index++;
      track.style.transform = `translateX(-${index * cardWidth}px)`;
      startSlider();
    };

    document.querySelector(".slider-btn.left").onclick = () => {
      clearInterval(interval);
      index = Math.max(index - 1, 0);
      track.style.transform = `translateX(-${index * cardWidth}px)`;
      startSlider();
    };

    // Pause on hover
    slider.addEventListener("mouseenter", () => clearInterval(interval));
    slider.addEventListener("mouseleave", startSlider);

    // Init
    window.addEventListener("load", startSlider);
    window.addEventListener("resize", () => {
      cardWidth = cards[0].offsetWidth + 20;
    });

  </script>

 
